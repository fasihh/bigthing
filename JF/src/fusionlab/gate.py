"""Detect-and-gate on real CMU-MOSEI with frozen models (no retraining).

A detector scores each modality of each clip; when the most suspicious modality exceeds its 99th percentile
on clean validation clips, that modality is treated as missing for that clip (the PoE model handles missing
modalities natively). 'soft' mode instead scales the modality's precision by 1 / r^2.

Detectors (all fitted on clean TRAIN clips only):
  input_maha  : Mahalanobis distance of the clip's pooled input statistics (mean, std over time)
  latent_maha : Mahalanobis distance of the expert's belief mean (feature-density / DDU style)
  crossmodal  : ridge-predict each modality's pooled statistics from the other modalities; residual
  electra     : [self-sup] classifier 'which modality was replaced?' trained on generated white-noise and
                random-clip swaps (ELECTRA replaced-token detection, applied to modalities)
  combo:a+b   : sum of threshold-normalised scores
Held-out corruptions never generated by any detector: noise at lambda=0.5, half-clip noise, gain fault,
dead sensor, time shuffle, two noisy modalities, and a swap with the most similar-looking clip.
"""
import math
import zlib

import numpy as np
import torch
import torch.nn as nn
from scipy.stats import norm
from sklearn.metrics import roc_auc_score

from .batching import get_batch
from .models import expert_beliefs
from .runtime import BASE, RT
from .stage2 import fused_output

Z90 = norm.ppf(0.95)
NAME = {'t': 'text', 'a': 'audio', 'v': 'video'}


# ----------------------------------------------------------------------------- conditions
def gate_conditions(include_heldout=True):
    out = [dict(name='clean', kind='clean')]
    for m in BASE:
        out += [dict(name=f'noise[{m}]', kind='noise', m=m, lam=1.0),
                dict(name=f'swap[{m}]', kind='swap', m=m)]
    if include_heldout:
        for m in BASE:
            out += [dict(name=f'noise[{m}]@0.5', kind='noise', m=m, lam=0.5, heldout=True),
                    dict(name=f'halfnoise[{m}]', kind='halfnoise', m=m, heldout=True),
                    dict(name=f'gain[{m}]', kind='gain', m=m, heldout=True),
                    dict(name=f'dead[{m}]', kind='dead', m=m, heldout=True),
                    dict(name=f'shuffle[{m}]', kind='shuffle', m=m, heldout=True),
                    dict(name=f'swapnn[{m}]', kind='swapnn', m=m, heldout=True)]
        for pair in (('t', 'a'), ('t', 'v'), ('a', 'v')):
            out.append(dict(name=f'noise2[{"".join(pair)}]', kind='noise2', ms=pair, heldout=True))
    return out


def nn_perm(F, m):
    """Hardest swap: the partner is the clip whose OTHER modalities look most alike (nearest neighbour in
    standardised pooled statistics), i.e. a plausible clip of a similar speaker / setting."""
    A = np.concatenate([F[k] for k in BASE if k != m], 1)
    A = torch.from_numpy((A - A.mean(0)) / (A.std(0) + 1e-6)).float()
    out = np.empty(len(A), dtype=np.int64)
    for i in range(0, len(A), 1024):
        d = torch.cdist(A[i:i + 1024], A)
        d[torch.arange(d.shape[0]), torch.arange(i, i + d.shape[0])] = float('inf')
        out[i:i + 1024] = d.argmin(1).numpy()
    return torch.from_numpy(out)


def _corrupt(b, cond, split, idx, g, perms, feat_mean):
    xs, masks = {}, {}
    k = cond['kind']
    if k == 'clean':
        return xs, masks
    ms = cond.get('ms', (cond.get('m'),))
    for m in ms:
        x, mk = b[m], b[m + 'm']
        mkf = mk.unsqueeze(-1).float()
        if k in ('noise', 'noise2'):
            lam = cond.get('lam', 1.0)
            eps = torch.randn(x.shape, device=RT.DEV, generator=g) * RT.FEAT_STD[m]
            xs[m] = (math.sqrt(1 - lam) * x + math.sqrt(lam) * eps) * mkf
        elif k == 'halfnoise':
            n_valid = mk.sum(1, keepdim=True)
            pos = torch.cumsum(mk.int(), 1)
            late = (pos > n_valid // 2) & mk
            eps = torch.randn(x.shape, device=RT.DEV, generator=g) * RT.FEAT_STD[m]
            xs[m] = torch.where(late.unsqueeze(-1), eps, x)
        elif k == 'gain':
            xs[m] = (feat_mean[m] + 3.0 * (x - feat_mean[m])) * mkf
        elif k == 'dead':
            xs[m] = feat_mean[m].expand_as(x) * mkf
        elif k == 'shuffle':
            order = torch.argsort(torch.rand(mk.shape, device=RT.DEV, generator=g), 1)
            xs[m] = torch.gather(x, 1, order.unsqueeze(-1).expand_as(x))
            masks[m] = torch.gather(mk, 1, order)
        elif k in ('swap', 'swapnn'):
            j = perms['swap'][idx] if k == 'swap' else perms['swapnn'][m][idx]
            xs[m] = RT.DATA[split][m][j].to(RT.DEV)
            masks[m] = RT.DATA[split][m + 'm'][j].to(RT.DEV)
    return xs, masks


def pooled(x, mk):
    mkf = mk.unsqueeze(-1).float()
    n = mkf.sum(1).clamp(min=1)
    mu = (x * mkf).sum(1) / n
    sd = (((x - mu.unsqueeze(1)) ** 2) * mkf).sum(1).div(n).clamp(min=0).sqrt()
    return torch.cat([mu, sd], -1)


@torch.no_grad()
def run_condition(model, split, cond, perms, feat_mean, seed=123, singles=False):
    """Corrupted inputs -> pooled stats, expert beliefs, and fused outputs for every availability pattern
    (full, drop-one; with singles=True also each modality alone)."""
    experts, fusion, head = model['experts'], model['fusion'], model['head']
    g = torch.Generator(device=RT.DEV).manual_seed(seed + zlib.crc32(cond['name'].encode()) % 10_000)
    n = RT.N_SPLIT[split]
    M = len(BASE)
    pats = [tuple(1.0 for _ in BASE)] + [tuple(0.0 if j == k else 1.0 for j in range(M)) for k in range(M)]
    if singles:
        pats += [tuple(1.0 if j == k else 0.0 for j in range(M)) for k in range(M)]
    out = dict(F={m: [] for m in BASE}, mu={m: [] for m in BASE}, lv={m: [] for m in BASE},
               fm={p: [] for p in pats}, fv={p: [] for p in pats})
    for i in range(0, n, 1024):
        idx = torch.arange(i, min(n, i + 1024))
        b = get_batch(split, idx, BASE, g)
        xs, masks = _corrupt(b, cond, split, idx, g, perms, feat_mean)
        mus, lvs = expert_beliefs(experts, b, masks, xs)
        for j, m in enumerate(BASE):
            x = xs.get(m, b[m]); mk = masks.get(m, b[m + 'm'])
            out['F'][m].append(pooled(x, mk).cpu())
            out['mu'][m].append(mus[:, j].cpu()); out['lv'][m].append(lvs[:, j].cpu())
        for p in pats:
            av = torch.tensor(p, device=RT.DEV).expand(len(idx), -1)
            mm, vv, *_ = fused_output(fusion, head, mus, lvs, av)
            out['fm'][p].append(mm.cpu()); out['fv'][p].append(vv.cpu())
    res = dict(F={m: torch.cat(v).numpy() for m, v in out['F'].items()},
               mu={m: torch.cat(v).numpy() for m, v in out['mu'].items()},
               lv={m: torch.cat(v).numpy() for m, v in out['lv'].items()},
               pred={p: (torch.cat(out['fm'][p]).numpy().astype(np.float64),
                         torch.cat(out['fv'][p]).numpy().astype(np.float64)) for p in pats},
               y=RT.DATA[split]['y'].numpy().astype(np.float64))
    res['mus'], res['lvs'] = None, None
    return res


@torch.no_grad()
def soft_predict(model, split, cond, perms, feat_mean, w, seed=123):
    """Fractional experts: modality m's precision scaled by w[:, m] (log-variance + log(1/w))."""
    experts, fusion, head = model['experts'], model['fusion'], model['head']
    g = torch.Generator(device=RT.DEV).manual_seed(seed + zlib.crc32(cond['name'].encode()) % 10_000)
    n = RT.N_SPLIT[split]
    W = torch.from_numpy(w).float()
    M_, V_ = [], []
    for i in range(0, n, 1024):
        idx = torch.arange(i, min(n, i + 1024))
        b = get_batch(split, idx, BASE, g)
        xs, masks = _corrupt(b, cond, split, idx, g, perms, feat_mean)
        mus, lvs = expert_beliefs(experts, b, masks, xs)
        lvs = lvs - torch.log(W[idx].clamp(min=1e-6)).to(RT.DEV).unsqueeze(-1)
        av = torch.ones(len(idx), len(BASE), device=RT.DEV)
        mm, vv, *_ = fused_output(fusion, head, mus, lvs, av)
        M_.append(mm.cpu()); V_.append(vv.cpu())
    return torch.cat(M_).numpy().astype(np.float64), torch.cat(V_).numpy().astype(np.float64)


# ----------------------------------------------------------------------------- detectors
class Gauss:
    def __init__(self, Z, shrink=0.1):
        self.mu = Z.mean(0)
        C = np.cov(Z, rowvar=False)
        C = (1 - shrink) * C + shrink * np.eye(len(C)) * np.trace(C) / len(C)
        self.P = np.linalg.inv(C)

    def __call__(self, Z):
        D = Z - self.mu
        return np.einsum('ij,jk,ik->i', D, self.P, D)


class InputMaha:
    def fit(self, tr):
        self.g = {m: Gauss(tr['F'][m]) for m in BASE}
        return self

    def score(self, r):
        return {m: self.g[m](r['F'][m]) for m in BASE}


class LatentMaha:
    def fit(self, tr):
        self.g = {m: Gauss(tr['mu'][m]) for m in BASE}
        return self

    def score(self, r):
        return {m: self.g[m](r['mu'][m]) for m in BASE}


class CrossModal:
    def fit(self, tr, alpha=10.0):
        F = tr['F']
        self.nm = {m: (F[m].mean(0), F[m].std(0) + 1e-6) for m in BASE}
        Z = {m: (F[m] - self.nm[m][0]) / self.nm[m][1] for m in BASE}
        self.W = {}
        for m in BASE:
            A = np.concatenate([Z[k] for k in BASE if k != m], 1)
            W = np.linalg.solve(A.T @ A + alpha * np.eye(A.shape[1]), A.T @ Z[m])
            self.W[m] = (W, (Z[m] - A @ W).var(0) + 1e-3)
        return self

    def score(self, r):
        Z = {m: (r['F'][m] - self.nm[m][0]) / self.nm[m][1] for m in BASE}
        out = {}
        for m in BASE:
            A = np.concatenate([Z[k] for k in BASE if k != m], 1)
            W, rv = self.W[m]
            out[m] = (((Z[m] - A @ W) ** 2) / rv).mean(1)
        tot = sum(out.values())
        return {m: out[m] - (tot - out[m]) / (len(BASE) - 1) for m in BASE}


class Electra:
    """[self-sup] which modality (if any) was replaced? Inputs: pooled stats of all modalities."""

    def fit(self, tr, tr_noise, seed=0, epochs=300):
        F, Fn = tr['F'], tr_noise
        self.nm = {m: (F[m].mean(0), F[m].std(0) + 1e-6) for m in BASE}
        Z = {m: torch.from_numpy((F[m] - self.nm[m][0]) / self.nm[m][1]).float() for m in BASE}
        Zn = {m: torch.from_numpy((Fn[m] - self.nm[m][0]) / self.nm[m][1]).float() for m in BASE}
        n = len(Z['t'])
        torch.manual_seed(seed)
        d = sum(z.shape[1] for z in Z.values())
        self.net = nn.Sequential(nn.Linear(d, 256), nn.GELU(), nn.Linear(256, 64), nn.GELU(), nn.Linear(64, 4))
        opt = torch.optim.Adam(self.net.parameters(), lr=1e-3, weight_decay=1e-4)
        gen = torch.Generator().manual_seed(seed)
        for ep in range(epochs):
            for i in range(0, n, 2048):
                idx = torch.randperm(n, generator=gen)[:2048]
                lab = torch.randint(0, 4, (len(idx),), generator=gen)
                isnoise = torch.rand(len(idx), generator=gen) < 0.5
                cols = []
                for j, m in enumerate(BASE):
                    z = Z[m][idx].clone()
                    sel = lab == j + 1
                    sw = torch.randint(0, n, (len(idx),), generator=gen)
                    z[sel & ~isnoise] = Z[m][sw][sel & ~isnoise]
                    z[sel & isnoise] = Zn[m][idx][sel & isnoise]
                    cols.append(z)
                loss = nn.functional.cross_entropy(self.net(torch.cat(cols, 1)), lab)
                opt.zero_grad(); loss.backward(); opt.step()
        self.net.eval()
        return self

    def score(self, r):
        Z = torch.from_numpy(np.concatenate([(r['F'][m] - self.nm[m][0]) / self.nm[m][1] for m in BASE], 1)).float()
        with torch.no_grad():
            p = torch.softmax(self.net(Z), 1).numpy()
        return {m: p[:, j + 1] for j, m in enumerate(BASE)}


class Combo:
    def __init__(self, dets):
        self.dets = dets

    def score(self, r):
        S = [d.score(r) for d in self.dets]
        return {m: sum(s[m] / d.thr[m] for s, d in zip(S, self.dets)) for m in BASE}


def calibrate(det, val_clean, q=0.99):
    s = det.score(val_clean)
    det.thr = {m: max(np.quantile(s[m], q), 1e-9) for m in BASE}
    return det


# ----------------------------------------------------------------------------- gate + metrics
def gate_drop(r, det):
    s = det.score(r)
    R = np.stack([s[m] / det.thr[m] for m in BASE], 1)
    full = tuple(1.0 for _ in BASE)
    mu, v = (a.copy() for a in r['pred'][full])
    j = R.argmax(1); flag = R.max(1) > 1
    for k in range(len(BASE)):
        p = tuple(0.0 if jj == k else 1.0 for jj in range(len(BASE)))
        sel = flag & (j == k)
        mu[sel], v[sel] = r['pred'][p][0][sel], r['pred'][p][1][sel]
    return mu, v, R


def metrics(y, mu, v, tau):
    v = v * tau
    return dict(MAE=np.mean(np.abs(y - mu)), NLL=np.mean(0.5 * np.log(2 * np.pi * v) + 0.5 * (y - mu) ** 2 / v),
                Cov90=np.mean(np.abs(y - mu) <= Z90 * np.sqrt(v)), SD=np.mean(np.sqrt(v)))


def auroc(clean_score, score):
    lab = np.r_[np.zeros(len(clean_score)), np.ones(len(score))]
    return roc_auc_score(lab, np.r_[clean_score, score])
